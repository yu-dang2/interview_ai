"""
개인정보 비식별화

이력서·JD 텍스트가 그대로 OpenAI 로 전송되는 것을 막는다. 수행계획서 II-2-나
"개인정보 비식별화 처리" 항목이며, 외부 사용자를 받는 순간 필수다.

적용 지점: 업로드·등록 시점(backend/routers/uploads.py, resume.py, jd.py).
저장 전에 한 번 마스킹하면 DB·LLM·로그 어디에도 원본이 남지 않는다.
나중에 마스킹하면 이미 저장된 원본이 남으므로 입구에서 막는 것이 중요하다.

마스킹 대상은 "그 자체로 개인을 특정할 수 있는 것"으로 한정한다.

    주민등록번호 · 전화번호 · 이메일 · 도로명/지번 주소 · 생년월일

이름은 뺐다. 한국어 이름은 일반 단어와 겹쳐(예: "한지민" vs "지민한다") 오탐이
많고, 이력서에서 이름을 지우면 resume_parser 가 지원자를 식별하지 못한다.
이름만으로는 특정이 어렵다는 판단도 있다. 필요해지면 resume_parsed 의 name 을
역으로 이용해 정확히 지우는 방식이 안전하다.

원문을 되살릴 수는 없다(복호화 아님). 이력서 내용 자체는 면접 질문 생성에
필요하므로 연락처류만 지우고 경력·기술 서술은 그대로 둔다.
"""

import re

# 각 패턴은 (이름, 정규식, 치환문자열).
# 순서가 중요하다. 주민번호를 먼저 지워야 그 안의 숫자열이 전화번호로 잡히지 않는다.
_PATTERNS: list[tuple[str, re.Pattern, str]] = [
    # 주민등록번호 940101-1234567 / 9401011234567
    (
        "rrn",
        re.compile(r"\b\d{6}\s*[-–]\s*[1-4]\d{6}\b"),
        "[주민번호]",
    ),
    # 이메일
    (
        "email",
        re.compile(r"\b[\w.+-]+@[\w-]+\.[\w.-]+\b"),
        "[이메일]",
    ),
    # 휴대폰·유선 010-1234-5678 / 01012345678 / 02-123-4567 / +82 10-1234-5678
    (
        "phone",
        re.compile(
            r"(?:\+?82[\s-]?)?"          # 국가번호(선택)
            r"0?\d{1,2}"                 # 지역/사업자 번호
            r"[\s.-]?\d{3,4}"
            r"[\s.-]?\d{4}"
            r"(?!\d)"
        ),
        "[전화번호]",
    ),
    # 도로명·지번 주소. 광역시/도로 시작해 도로명(로/길) 또는 법정동(동/읍/면/리)으로
    # 끝나는 덩어리를 잡는다. 끝을 이 접미사로 못박아야 "경기" 같은 단어가 본문에
    # 나왔을 때 오탐하지 않는다.
    (
        "address",
        re.compile(
            r"(?:서울|부산|대구|인천|광주|대전|울산|세종|경기|강원|충북|충남|"
            r"전북|전남|경북|경남|제주)"
            r"(?:\S*(?:시|도))?"                    # 특별시·광역시·도 (선택)
            r"(?:\s*\S+(?:시|군|구)){0,2}"          # 시·군·구 (최대 2단계)
            r"(?:\s*\S+(?:로|길|동|읍|면|리))"      # 도로명 또는 법정동 (필수)
            r"[^\n,]{0,30}"                        # 번지·상세주소
        ),
        "[주소]",
    ),
    # 생년월일. 라벨이 앞에 붙은 경우만 지운다.
    # 날짜 형태만으로 잡으면 "2023.03.01 입사" 같은 경력 날짜까지 지워져
    # 면접 질문 생성에 필요한 정보가 사라진다.
    (
        "birth",
        re.compile(
            r"(?:생년월일|생일|출생일?)\s*[:：]?\s*"
            r"(?:19|20)\d{2}\s*[.\-/년]\s*(?:0?[1-9]|1[0-2])\s*[.\-/월]\s*"
            r"(?:0?[1-9]|[12]\d|3[01])(?:\s*일)?"
        ),
        "[생년월일]",
    ),
]


def mask_personal_info(text: str) -> str:
    """개인 식별 정보를 자리표시자로 바꾼 텍스트를 반환한다."""
    if not text:
        return text
    for _, pattern, placeholder in _PATTERNS:
        text = pattern.sub(placeholder, text)
    return text


def masking_report(text: str) -> dict[str, int]:
    """
    어떤 항목이 몇 건 잡혔는지. 로그·검증용이며 원문은 남기지 않는다.

    운영 중에는 이 값만 로그에 남겨 마스킹이 실제로 동작하는지 확인한다.
    """
    if not text:
        return {}
    counts: dict[str, int] = {}
    remaining = text
    for name, pattern, placeholder in _PATTERNS:
        found = pattern.findall(remaining)
        if found:
            counts[name] = len(found)
        remaining = pattern.sub(placeholder, remaining)
    return counts
